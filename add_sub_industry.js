const txt = fs.readFileSync(path.join(__dirname, 'tomorrow_active.txt'), 'utf8').replace(/^﻿/, '');
const lines = txt.split('\n').filter(Boolean);
const headers = lines[0].split('\t');
const rows = lines.slice(1).map(l => l.split('\t'));

// Insert 次產業 after 細產業 (index 3 -> insert at 4)
const IND_IDX = 3;
const newHeaders = [...headers.slice(0, IND_IDX+1), '次產業', ...headers.slice(IND_IDX+1)];

const newRows = rows.map(r => {
  const code = r[1];
  const sub = SUB_INDUSTRY[code] || '(未分類)';
  return [...r.slice(0, IND_IDX+1), sub, ...r.slice(IND_IDX+1)];
});

fs.writeFileSync(path.join(__dirname, 'tomorrow_active.txt'),
  '﻿' + newHeaders.join('\t') + '\n' + newRows.map(r => r.join('\t')).join('\n') + '\n', 'utf8');

// 統計
const subCount = {};
newRows.forEach(r => { subCount[r[4]] = (subCount[r[4]]||0)+1; });
console.log('次產業分布:');
Object.entries(subCount).sort((a,b) => b[1]-a[1]).forEach(([k,v]) => console.log('  ' + k + ':', v));

const missing = newRows.filter(r => r[4] === '(未分類)');
if (missing.length) {
  console.log('\n未分類 (need review):');
  missing.forEach(r => console.log('  ' + r[0] + ' ' + r[1] + ' ' + r[2] + ' (' + r[3] + ')'));
}
